    closeCheckoutModal: ui.closeCheckoutModal,
    processCheckout: () => session.processCheckout({ router }),
    probePendingCheckout: (opts) => session.probePendingCheckout({ heartbeat: opts?.heartbeat === true, router }),
    discardPendingCheckout: session.discardPendingCheckout,
    dismissPendingCheckoutUnreadable: session.dismissPendingCheckoutUnreadable,
    openCashDrawer: session.openCashDrawer,
