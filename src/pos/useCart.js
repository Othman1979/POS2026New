    cart: s.cart,
    selectedCartIndex: s.selectedCartIndex,
    orderNote: s.orderNote,
    orderDiscount: s.orderDiscount,
    orderTypes: s.orderTypes,
    selectedOrderType: s.selectedOrderType,
