    cashShortfall: s.cashShortfall,
    splitBalanceDue: s.splitBalanceDue,
    selectedOrderTypeRequiresHash: s.selectedOrderTypeRequiresHash,
    isDirectPlatformCheckout: s.isDirectPlatformCheckout,
    defaultOrderTypeId: s.defaultOrderTypeId,
    serviceChargeEnabled: s.serviceChargeEnabled,
    serviceChargePercentage: s.serviceChargePercentage,
    autoApplyServiceCharge: s.autoApplyServiceCharge,
    canRemoveAutoServiceCharge: s.canRemoveAutoServiceCharge,
    canApplyDiscount: s.canApplyDiscount,
    canVoidActiveTable: s.canVoidActiveTable,
    hasSavedTableItems: s.hasSavedTableItems,
    canRemoveSelectedCartItem: s.canRemoveSelectedCartItem,
    canClearCart: s.canClearCart,
    canApplyServiceCharge: s.canApplyServiceCharge,
    canCheckout: s.canCheckout,
    canCheckoutTable: s.canCheckoutTable,
    canPrintCheck: s.canPrintCheck,

    // ui state (refs)
    showCheckoutModal: u.showCheckoutModal,
    paymentMethod: u.paymentMethod,
    amountTendered: u.amountTendered,
    splitCardAmount: u.splitCardAmount,
    splitCashTendered: u.splitCashTendered,
