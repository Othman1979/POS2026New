// @/pos/useCart.js — logic-free facade over the order stores.
// State + logic live in stores/orderSessionStore.js and stores/orderUiStore.js.
// This file ONLY renames/re-exports. Do not add branches or derivations here.
import { storeToRefs } from 'pinia';
import { useRouter } from 'vue-router';
import { useOrderSessionStore } from './stores/orderSessionStore.js';
import { useOrderUiStore } from './stores/orderUiStore.js';

