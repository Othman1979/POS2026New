    isHolding: u.isHolding,
    checkoutError: u.checkoutError,
    numpadInput: u.numpadInput,
    numpadMode: u.numpadMode,
    quickTargetAmount: u.quickTargetAmount,
    mobileCartOpen: u.mobileCartOpen,
    showCustomerDrawer: u.showCustomerDrawer,
    activeModal: u.activeModal,
    modalTarget: u.modalTarget,
    tempNote: u.tempNote,
    tempDiscount: u.tempDiscount,
    isCustomerLoading: u.isCustomerLoading,
